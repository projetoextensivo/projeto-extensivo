import { test, expect } from '@playwright/test';
test('fluxos completos e layout responsivo',async({page})=>{
 const errors=[];page.on('pageerror',error=>errors.push(error.message));
 await page.goto('/');
 await expect(page.getByRole('heading',{name:'Entrar',exact:true})).toBeVisible();
 await page.screenshot({path:'artifacts/screenshots/login.png',fullPage:true,animations:"disabled"});
 await page.getByRole('button',{name:'Explorar demonstração'}).click();
 await expect(page.getByRole('heading',{name:'Nossa agenda'})).toBeVisible();
 await expect(page.locator('.month-grid')).toBeVisible();
 await page.getByRole('button',{name:'Semana',exact:true}).click();
 await expect(page.locator('.time-grid')).toBeVisible();
 await page.screenshot({path:'artifacts/screenshots/agenda.png',fullPage:true,animations:"disabled"});
 await page.getByRole('link',{name:'Pacientes',exact:true}).click();
 await page.getByRole('button',{name:'Novo paciente',exact:true}).click();
 await page.getByLabel('Nome completo').fill('Paciente Navegador');
 await page.getByLabel('Idade',{exact:true}).fill('32');
 await page.getByLabel('Telefone',{exact:true}).fill('(11) 98888-7777');
 await page.getByLabel('E-mail',{exact:true}).fill('browser@example.com');
 await page.getByRole('button',{name:'Cadastrar paciente',exact:true}).click();
 await expect(page.getByRole('dialog')).toBeHidden();
 await page.getByRole('searchbox').fill('Paciente Navegador');
 await expect(page.getByRole('button',{name:'Paciente Navegador Particular',exact:true})).toBeVisible();
 await page.reload();
 await page.getByRole('searchbox').fill('Paciente Navegador');
 await page.getByRole('button',{name:/Abrir prontuário de Paciente Navegador/}).click();
 await expect(page.getByRole('heading',{name:'Prontuário',exact:true})).toBeVisible();
 await page.getByRole('button',{name:'Novo atendimento',exact:true}).click();
 await page.getByLabel('Título do atendimento').fill('Avaliação de teste');
 await page.getByLabel('Dente (opcional)').fill('26');
 await page.getByLabel('Descrição clínica').fill('Paciente sem queixas. Orientações de higiene realizadas.');
 await page.getByRole('button',{name:'Salvar atendimento'}).click();
 await expect(page.getByRole('dialog')).toBeHidden();
 await expect(page.getByRole('heading',{name:'Avaliação de teste'})).toBeVisible();
 await page.getByRole('button',{name:'Dente 26: Sadio. Registrar atendimento.'}).count();
 await page.getByRole('link',{name:'Dashboard',exact:true}).click();
 await expect(page.getByRole('heading',{name:'Dashboard',exact:true})).toBeVisible();
 await expect(page.locator('.kpi-card')).toHaveCount(3);
 await page.screenshot({path:'artifacts/screenshots/dashboard.png',fullPage:true,animations:"disabled"});
 await page.getByRole('link',{name:'Procedimentos',exact:true}).click();
 await page.getByRole('button',{name:'Estética',exact:true}).click();
 await expect(page.getByRole('heading',{name:'Clareamento Dental'})).toBeVisible();
 await expect(page.locator('.procedure-card')).toHaveCount(1);
 await page.getByRole('button',{name:'Todos',exact:true}).click();
 await page.getByRole('button',{name:'Novo procedimento'}).click();
 await page.getByLabel('Nome do procedimento').fill('Procedimento Navegador');
 await page.getByLabel('Duração (minutos)').fill('30');
 await page.getByLabel('Valor (R$)').fill('120');
 await page.getByRole('button',{name:'Criar procedimento'}).click();
 await expect(page.getByRole('dialog')).toBeHidden();
 await expect(page.getByRole('heading',{name:'Procedimento Navegador'})).toBeVisible();
 await page.getByRole('link',{name:'Agenda',exact:true}).click();
 await page.getByRole('button',{name:'Novo agendamento'}).click();
 await page.getByLabel('Paciente',{exact:true}).selectOption({label:'Paciente Navegador'});
 await page.getByLabel('Procedimento',{exact:true}).selectOption({label:'Procedimento Navegador'});
 await page.getByLabel('Data',{exact:true}).fill('2030-10-21');
 await page.getByLabel('Horário',{exact:true}).fill('11:00');
 await page.getByRole('button',{name:'Agendar consulta'}).click();
 await expect(page.getByRole('dialog')).toBeHidden();
 await page.getByRole('button',{name:'Novo agendamento'}).click();
 await page.getByLabel('Paciente',{exact:true}).selectOption({label:'Paciente Navegador'});
 await page.getByLabel('Procedimento',{exact:true}).selectOption({label:'Procedimento Navegador'});
 await page.getByLabel('Data',{exact:true}).fill('2030-10-21');
 await page.getByLabel('Horário',{exact:true}).fill('11:15');
 await page.getByRole('button',{name:'Agendar consulta'}).click();
 await expect(page.getByRole('alert')).toContainText('Este horário já está ocupado');
 await page.keyboard.press('Escape');
 await expect(page.getByRole('dialog')).toBeHidden();
 for(const width of [1024,768,390]){
  await page.setViewportSize({width,height:900});
  if(width<1024)await page.getByRole('button',{name:'Abrir menu'}).click();
  await page.getByRole('link',{name:'Dashboard',exact:true}).click();
  await expect(page.getByRole('heading',{name:'Dashboard',exact:true})).toBeVisible();
  expect(await page.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth)).toBe(true);
  if(width===390)await page.screenshot({path:'artifacts/screenshots/mobile.png',fullPage:true,animations:"disabled"});
 }
 expect(errors).toEqual([]);
});
test('cadastro de conta e validacao dos campos',async({page})=>{
 await page.goto('/');
 await page.getByRole('button',{name:'Cadastre-se',exact:true}).click();
 await page.getByLabel('Nome completo').fill('Equipe Teste');
 await page.getByLabel('E-mail',{exact:true}).fill('equipe@example.com');
 await page.getByLabel('Cargo',{exact:true}).selectOption('Recepcionista');
 await page.getByLabel('Senha',{exact:true}).fill('Senha@2026');
 await page.getByLabel('Confirmar senha',{exact:true}).fill('Outra@2026');
 await page.getByRole('checkbox').check();
 await page.getByRole('button',{name:'Criar conta',exact:true}).click();
 await expect(page.getByRole('alert')).toContainText('As senhas não coincidem');
 await page.getByLabel('Confirmar senha',{exact:true}).fill('Senha@2026');
 await page.getByRole('button',{name:'Criar conta',exact:true}).click();
 await expect(page.getByRole('heading',{name:'Nossa agenda'})).toBeVisible();
 await page.getByRole('button',{name:'Sair da conta',exact:true}).click();
 await page.getByRole('dialog').getByRole('button',{name:'Sair da conta',exact:true}).click();
 await expect(page.getByRole('heading',{name:'Entrar',exact:true})).toBeVisible();
});
